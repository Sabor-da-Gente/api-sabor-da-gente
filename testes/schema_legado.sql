create table public.categorias (
  id   bigint generated by default as identity primary key,
  nome text not null unique
);

create table public.produtos (
  id           bigint generated by default as identity primary key,
  categoria_id bigint not null references public.categorias (id),
  nome         text not null,
  descricao    text,
  imagem_url   text,
  preco        integer not null check (preco >= 0),
  destaque     boolean not null default false,
  ativo        boolean not null default true,
  criado_em    timestamptz not null default now()
);

create table public.pedidos (
  id               uuid primary key default gen_random_uuid(),
  numero           bigint generated always as identity unique,
  cliente_nome     text,
  cliente_telefone text,
  tipo_entrega     text not null default 'retirada',
  endereco_entrega text,
  forma_pagamento  text,
  troco_para       integer,
  total            integer not null default 0,
  status           text not null default 'recebido'
    check (status in ('recebido', 'em_preparo', 'saiu_para_entrega', 'entregue', 'cancelado')),
  criado_em        timestamptz not null default now()
);

create table public.itens_pedido (
  id             bigint generated by default as identity primary key,
  pedido_id      uuid not null references public.pedidos (id) on delete cascade,
  nome           text not null,
  sabores        text[],
  quantidade     integer not null default 1,
  preco_unitario integer not null default 0
);

