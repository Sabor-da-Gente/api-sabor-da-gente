-- Sabor da Gente: compatibilidade com o banco existente.
-- Esta migration é aditiva: preserva IDs e colunas antigas.
-- Não converte pedidos.id de UUID para BIGINT.

begin;

create extension if not exists pgcrypto;

-- =========================================================
-- PERFIS E ENDEREÇOS
-- =========================================================

create table if not exists public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  telefone text,
  tipo text not null default 'cliente'
    check (tipo in ('cliente', 'admin')),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.enderecos (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null default auth.uid()
    references public.perfis(id) on delete cascade,
  apelido text,
  logradouro text not null,
  numero text not null,
  complemento text,
  bairro text not null,
  cidade text not null,
  uf text not null default 'PB' check (length(uf) = 2),
  cep text,
  referencia text,
  principal boolean not null default false,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create index if not exists idx_enderecos_usuario
  on public.enderecos(usuario_id);

-- =========================================================
-- COMPLEMENTOS DO CATÁLOGO
-- As tabelas categorias e produtos existentes são preservadas.
-- =========================================================

alter table public.categorias
  add column if not exists slug text,
  add column if not exists tipo text not null default 'produtos',
  add column if not exists icone text,
  add column if not exists ordem integer not null default 0,
  add column if not exists ativa boolean not null default true;

alter table public.produtos
  add column if not exists ingredientes text,
  add column if not exists atualizado_em timestamptz not null default now();

create table if not exists public.tamanhos (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  fatias integer not null check (fatias > 0),
  max_sabores integer not null default 1
    check (max_sabores between 1 and 4),
  ordem integer not null default 0,
  ativo boolean not null default true
);

create table if not exists public.massas (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  acrescimo integer not null default 0 check (acrescimo >= 0),
  ativo boolean not null default true
);

create table if not exists public.sabores (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  descricao text,
  ingredientes text,
  imagem_url text,
  destaque boolean not null default false,
  ativo boolean not null default true
);

create table if not exists public.sabor_precos (
  sabor_id bigint not null references public.sabores(id),
  tamanho_id bigint not null references public.tamanhos(id),
  preco integer not null check (preco >= 0),
  primary key (sabor_id, tamanho_id)
);

create index if not exists idx_sabor_precos_tamanho
  on public.sabor_precos(tamanho_id);

create table if not exists public.adicionais (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  preco integer not null check (preco >= 0),
  ativo boolean not null default true
);

create table if not exists public.cupons (
  id bigint generated by default as identity primary key,
  codigo text not null,
  tipo text not null check (tipo in ('percentual', 'valor_fixo')),
  valor integer not null check (valor > 0),
  valor_minimo_pedido integer not null default 0,
  valido_de timestamptz,
  valido_ate timestamptz,
  usos_maximos integer,
  ativo boolean not null default true,
  check (tipo <> 'percentual' or valor <= 100)
);

create unique index if not exists uq_cupons_codigo
  on public.cupons(lower(codigo));

create table if not exists public.configuracoes (
  chave text primary key,
  valor text not null
);

-- =========================================================
-- PEDIDOS: preservar o UUID existente e as colunas antigas.
-- Campos novos ficam inicialmente opcionais para não invalidar
-- os registros atuais nem exigir migração de dados de clientes.
-- =========================================================

alter table public.pedidos
  add column if not exists cliente_id uuid
    references public.perfis(id),
  add column if not exists endereco_id bigint
    references public.enderecos(id),
  add column if not exists observacao text,
  add column if not exists cupom_id bigint
    references public.cupons(id),
  add column if not exists subtotal integer,
  add column if not exists desconto integer not null default 0,
  add column if not exists taxa_entrega integer not null default 0,
  add column if not exists atualizado_em timestamptz not null default now();

create index if not exists idx_pedidos_cliente
  on public.pedidos(cliente_id);

create index if not exists idx_pedidos_endereco
  on public.pedidos(endereco_id);

create index if not exists idx_pedidos_cupom
  on public.pedidos(cupom_id);

-- =========================================================
-- ITENS: manter pedido_id UUID e as colunas antigas.
-- As colunas novas são adicionadas sem remover nome/sabores.
-- =========================================================

alter table public.itens_pedido
  add column if not exists tipo text,
  add column if not exists produto_id bigint
    references public.produtos(id),
  add column if not exists tamanho_id bigint
    references public.tamanhos(id),
  add column if not exists massa_id bigint
    references public.massas(id),
  add column if not exists descricao text,
  add column if not exists subtotal integer,
  add column if not exists observacao text;

create index if not exists idx_itens_pedido_produto
  on public.itens_pedido(produto_id);

create index if not exists idx_itens_pedido_tamanho
  on public.itens_pedido(tamanho_id);

create index if not exists idx_itens_pedido_massa
  on public.itens_pedido(massa_id);

-- =========================================================
-- DETALHES DOS ITENS, HISTÓRICO, PAGAMENTOS E FAVORITOS
-- IDs de pedido nestas tabelas continuam sendo UUID.
-- =========================================================

create table if not exists public.itens_pedido_sabores (
  item_id bigint not null
    references public.itens_pedido(id) on delete cascade,
  sabor_id bigint not null references public.sabores(id),
  nome text not null,
  preco integer not null,
  primary key (item_id, sabor_id)
);

create index if not exists idx_itens_sabores_sabor
  on public.itens_pedido_sabores(sabor_id);

create table if not exists public.itens_pedido_adicionais (
  item_id bigint not null
    references public.itens_pedido(id) on delete cascade,
  adicional_id bigint not null references public.adicionais(id),
  nome text not null,
  preco integer not null,
  primary key (item_id, adicional_id)
);

create index if not exists idx_itens_adicionais_adicional
  on public.itens_pedido_adicionais(adicional_id);

create table if not exists public.pedido_status_historico (
  id bigint generated by default as identity primary key,
  pedido_id uuid not null
    references public.pedidos(id) on delete cascade,
  status text not null,
  alterado_por uuid references public.perfis(id),
  criado_em timestamptz not null default now()
);

create index if not exists idx_historico_pedido
  on public.pedido_status_historico(pedido_id);

create table if not exists public.pagamentos (
  id bigint generated by default as identity primary key,
  pedido_id uuid not null unique
    references public.pedidos(id) on delete cascade,
  forma text not null check (forma in ('pix', 'cartao', 'dinheiro')),
  status text not null default 'pendente'
    check (status in ('pendente', 'aprovado', 'recusado', 'estornado')),
  valor integer not null check (valor >= 0),
  troco_para integer,
  criado_em timestamptz not null default now(),
  check (
    troco_para is null
    or (forma = 'dinheiro' and troco_para >= valor)
  )
);

create table if not exists public.favoritos (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null default auth.uid()
    references public.perfis(id) on delete cascade,
  produto_id bigint references public.produtos(id),
  sabor_id bigint references public.sabores(id),
  criado_em timestamptz not null default now(),
  check ((produto_id is null) <> (sabor_id is null))
);

create unique index if not exists uq_favorito_produto
  on public.favoritos(usuario_id, produto_id)
  where produto_id is not null;

create unique index if not exists uq_favorito_sabor
  on public.favoritos(usuario_id, sabor_id)
  where sabor_id is not null;

create index if not exists idx_favoritos_produto
  on public.favoritos(produto_id);

create index if not exists idx_favoritos_sabor
  on public.favoritos(sabor_id);

commit;
