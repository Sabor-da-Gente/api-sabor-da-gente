-- Mantém atualizado_em em dia
create function public.tocar_atualizado_em()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;

create trigger trg_perfis_atualizado before update on public.perfis
  for each row execute function public.tocar_atualizado_em();
create trigger trg_produtos_atualizado before update on public.produtos
  for each row execute function public.tocar_atualizado_em();
create trigger trg_pedidos_atualizado before update on public.pedidos
  for each row execute function public.tocar_atualizado_em();

-- Cria o perfil automaticamente quando alguém se cadastra no Auth.
-- O app manda nome e telefone em options.data no signUp.
create function public.criar_perfil_novo_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfis (id, nome, telefone)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'nome', ''), split_part(new.email, '@', 1)),
    nullif(new.raw_user_meta_data ->> 'telefone', '')
  );
  return new;
end;
$$;

create trigger trg_auth_novo_usuario after insert on auth.users
  for each row execute function public.criar_perfil_novo_usuario();
