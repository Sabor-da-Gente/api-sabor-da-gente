-- =====================================================================
-- Sabor da Gente — 1/5: tabelas
--
-- Mesmo modelo do docs/modelo-de-dados.md, agora em PostgreSQL/Supabase.
-- Convenções:
--   * Dinheiro: INTEGER em centavos (R$ 45,00 = 4500).
--   * Datas: TIMESTAMPTZ.
--   * Catálogo nunca é apagado: usa-se ativo = false.
--   * Pedidos guardam "fotografias" de nomes e preços da hora da compra.
--   * Usuários e senhas ficam no Supabase Auth (auth.users);
--     aqui guardamos só o perfil (nome, telefone, tipo).
-- =====================================================================

-- ---------------------------------------------------------------------
-- PERFIS (1 para 1 com auth.users). Cliente e admin = coluna tipo.
-- ---------------------------------------------------------------------
create table public.perfis (
  id            uuid primary key references auth.users (id) on delete cascade,
  nome          text not null,
  telefone      text,
  tipo          text not null default 'cliente' check (tipo in ('cliente', 'admin')),
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table public.enderecos (
  id          bigint generated always as identity primary key,
  usuario_id  uuid not null default auth.uid() references public.perfis (id) on delete cascade,
  apelido     text,
  logradouro  text not null,
  numero      text not null,
  complemento text,
  bairro      text not null,
  cidade      text not null,
  uf          text not null default 'PB' check (length(uf) = 2),
  cep         text,
  referencia  text,
  principal   boolean not null default false,
  ativo       boolean not null default true,
  criado_em   timestamptz not null default now()
);
create index idx_enderecos_usuario on public.enderecos (usuario_id);

-- ---------------------------------------------------------------------
-- CATÁLOGO
-- ---------------------------------------------------------------------
create table public.categorias (
  id     bigint generated by default as identity primary key,
  nome   text not null unique,
  slug   text not null unique,
  -- 'pizza' abre o "Monte sua pizza"; 'produtos' lista produtos de preço fixo
  tipo   text not null default 'produtos' check (tipo in ('pizza', 'produtos')),
  icone  text,
  ordem  integer not null default 0,
  ativa  boolean not null default true
);

-- Produtos de preço fixo: esfihas, bebidas, combos, sobremesas
create table public.produtos (
  id            bigint generated by default as identity primary key,
  categoria_id  bigint not null references public.categorias (id),
  nome          text not null,
  descricao     text,
  ingredientes  text,
  imagem_url    text,
  preco         integer not null check (preco >= 0),
  destaque      boolean not null default false,
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index idx_produtos_categoria on public.produtos (categoria_id);

-- Pizza montável: tamanho + massa + 1..N sabores + adicionais
create table public.tamanhos (
  id          bigint generated by default as identity primary key,
  nome        text not null unique,
  fatias      integer not null check (fatias > 0),
  max_sabores integer not null default 1 check (max_sabores between 1 and 4),
  ordem       integer not null default 0,
  ativo       boolean not null default true
);

create table public.massas (
  id        bigint generated by default as identity primary key,
  nome      text not null unique,
  acrescimo integer not null default 0 check (acrescimo >= 0),
  ativo     boolean not null default true
);

create table public.sabores (
  id           bigint generated by default as identity primary key,
  nome         text not null unique,
  descricao    text,
  ingredientes text,
  imagem_url   text,
  destaque     boolean not null default false,
  ativo        boolean not null default true
);

-- Preço de cada sabor em cada tamanho. Sem linha = indisponível no tamanho.
create table public.sabor_precos (
  sabor_id   bigint not null references public.sabores (id),
  tamanho_id bigint not null references public.tamanhos (id),
  preco      integer not null check (preco >= 0),
  primary key (sabor_id, tamanho_id)
);
create index idx_sabor_precos_tamanho on public.sabor_precos (tamanho_id);

create table public.adicionais (
  id    bigint generated by default as identity primary key,
  nome  text not null unique,
  preco integer not null check (preco >= 0),
  ativo boolean not null default true
);

-- Cupons (fase 2)
create table public.cupons (
  id                  bigint generated by default as identity primary key,
  codigo              text not null,
  tipo                text not null check (tipo in ('percentual', 'valor_fixo')),
  valor               integer not null check (valor > 0), -- % (1..100) ou centavos
  valor_minimo_pedido integer not null default 0,
  valido_de           timestamptz,
  valido_ate          timestamptz,
  usos_maximos        integer,                            -- null = ilimitado
  ativo               boolean not null default true,
  check (tipo <> 'percentual' or valor <= 100)
);
create unique index uq_cupons_codigo on public.cupons (lower(codigo));

-- Configurações gerais (chave/valor): taxa_entrega, regra_preco_pizza
create table public.configuracoes (
  chave text primary key,
  valor text not null
);

-- ---------------------------------------------------------------------
-- PEDIDOS (gravados só pela função criar_pedido)
-- ---------------------------------------------------------------------
create table public.pedidos (
  id               bigint generated always as identity primary key,
  cliente_id       uuid not null references public.perfis (id),
  tipo_entrega     text not null check (tipo_entrega in ('entrega', 'retirada')),
  endereco_id      bigint references public.enderecos (id),
  endereco_entrega text,  -- fotografia do endereço na hora do pedido
  status           text not null default 'realizado'
                   check (status in ('realizado', 'em_preparacao', 'saiu_para_entrega',
                                     'pronto_para_retirada', 'entregue', 'cancelado')),
  observacao       text check (length(observacao) <= 300),
  cupom_id         bigint references public.cupons (id),
  subtotal         integer not null check (subtotal >= 0),
  desconto         integer not null default 0 check (desconto >= 0),
  taxa_entrega     integer not null default 0 check (taxa_entrega >= 0),
  total            integer not null check (total >= 0),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now(),
  check (tipo_entrega = 'retirada' or (endereco_id is not null and endereco_entrega is not null)),
  check (total = subtotal - desconto + taxa_entrega)
);
create index idx_pedidos_cliente on public.pedidos (cliente_id);
create index idx_pedidos_status on public.pedidos (status);
create index idx_pedidos_criado_em on public.pedidos (criado_em);
create index idx_pedidos_endereco on public.pedidos (endereco_id);
create index idx_pedidos_cupom on public.pedidos (cupom_id);

-- Cada linha do pedido: 'produto' (preço fixo) ou 'pizza' (montada)
create table public.itens_pedido (
  id             bigint generated always as identity primary key,
  pedido_id      bigint not null references public.pedidos (id) on delete cascade,
  tipo           text not null check (tipo in ('produto', 'pizza')),
  produto_id     bigint references public.produtos (id),
  tamanho_id     bigint references public.tamanhos (id),
  massa_id       bigint references public.massas (id),
  descricao      text not null,
  quantidade     integer not null check (quantidade between 1 and 50),
  preco_unitario integer not null check (preco_unitario >= 0),
  subtotal       integer not null check (subtotal >= 0),
  observacao     text check (length(observacao) <= 200),
  check (
    (tipo = 'produto' and produto_id is not null and tamanho_id is null and massa_id is null)
    or
    (tipo = 'pizza' and produto_id is null and tamanho_id is not null and massa_id is not null)
  ),
  check (subtotal = preco_unitario * quantidade)
);
create index idx_itens_pedido_pedido on public.itens_pedido (pedido_id);
create index idx_itens_pedido_produto on public.itens_pedido (produto_id);
create index idx_itens_pedido_tamanho on public.itens_pedido (tamanho_id);
create index idx_itens_pedido_massa on public.itens_pedido (massa_id);

create table public.itens_pedido_sabores (
  item_id  bigint not null references public.itens_pedido (id) on delete cascade,
  sabor_id bigint not null references public.sabores (id),
  nome     text not null,     -- fotografia
  preco    integer not null,  -- fotografia do preço no tamanho
  primary key (item_id, sabor_id)
);
create index idx_itens_sabores_sabor on public.itens_pedido_sabores (sabor_id);

create table public.itens_pedido_adicionais (
  item_id      bigint not null references public.itens_pedido (id) on delete cascade,
  adicional_id bigint not null references public.adicionais (id),
  nome         text not null,
  preco        integer not null,
  primary key (item_id, adicional_id)
);
create index idx_itens_adicionais_adicional on public.itens_pedido_adicionais (adicional_id);

-- Linha do tempo do acompanhamento
create table public.pedido_status_historico (
  id           bigint generated always as identity primary key,
  pedido_id    bigint not null references public.pedidos (id) on delete cascade,
  status       text not null,
  alterado_por uuid references public.perfis (id),
  criado_em    timestamptz not null default now()
);
create index idx_historico_pedido on public.pedido_status_historico (pedido_id);
create index idx_historico_alterado_por on public.pedido_status_historico (alterado_por);

-- Pagamento simulado (1 por pedido)
create table public.pagamentos (
  id         bigint generated always as identity primary key,
  pedido_id  bigint not null unique references public.pedidos (id) on delete cascade,
  forma      text not null check (forma in ('pix', 'cartao', 'dinheiro')),
  status     text not null default 'pendente'
             check (status in ('pendente', 'aprovado', 'recusado', 'estornado')),
  valor      integer not null check (valor >= 0),
  troco_para integer,
  criado_em  timestamptz not null default now(),
  check (troco_para is null or (forma = 'dinheiro' and troco_para >= valor))
);

-- ---------------------------------------------------------------------
-- FAVORITOS (fase 2): produto OU sabor
-- ---------------------------------------------------------------------
create table public.favoritos (
  id         bigint generated always as identity primary key,
  usuario_id uuid not null default auth.uid() references public.perfis (id) on delete cascade,
  produto_id bigint references public.produtos (id),
  sabor_id   bigint references public.sabores (id),
  criado_em  timestamptz not null default now(),
  check ((produto_id is null) <> (sabor_id is null))
);
create unique index uq_favorito_produto on public.favoritos (usuario_id, produto_id) where produto_id is not null;
create unique index uq_favorito_sabor on public.favoritos (usuario_id, sabor_id) where sabor_id is not null;
create index idx_favoritos_produto on public.favoritos (produto_id);
create index idx_favoritos_sabor on public.favoritos (sabor_id);

